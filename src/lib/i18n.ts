export type Dict = { [K in keyof (typeof dict)["en"]]: string };

export const SUPPORTED_LANGS: Lang[] = ["en", "uk", "ru", "zh", "es", "ar"];

export function useT(): Dict {
  const { lang } = useProfile();
  return (dict[lang] ?? dict.en) as Dict;
}

export function langLabel(l: Lang): string {
  switch (l) {
    case "uk":
      return "Українська";
    case "en":
      return "English";
    case "ru":
      return "Русский";
    case "zh":
      return "中文";
    case "es":
      return "Español";
    case "ar":
      return "العربية";
    default: {
      const _exhaustive: never = l;
      return _exhaustive;
    }
  }
}
